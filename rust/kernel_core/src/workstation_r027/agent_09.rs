//! R027/09: built-in safe project scaffolding into real RamFs file entries.
//! No external package download or arbitrary script execution.
use super::Error;
use crate::batch7_ramfs::{RamFs,PATH_MAX,CONTENT_MAX};
#[derive(Clone,Copy,Debug,PartialEq,Eq)]
pub enum Template{RustLibrary,RustCommand,Readme}
pub fn content(template:Template)->&'static[u8]{
 match template{
  Template::RustLibrary=>b"pub fn run() -> bool { true }\n",
  Template::RustCommand=>b"pub fn main() { }\n",
  Template::Readme=>b"# Project\n\nGenerated by IndianOS.\n"
 }
}
pub fn generate<const F:usize>(fs:&mut RamFs<F>,expected:u64,
 path:&[u8],template:Template)->Result<u64,Error>{
 if fs.version()!=expected{return Err(Error::Stale);}
 if path.len()<2||path.len()>PATH_MAX||path[0]!=b'/'||
 path.windows(2).any(|x|x==b".."){return Err(Error::Invalid);}
 if fs.metadata(path).is_ok(){return Err(Error::Conflict);}
 fs.replace(path,content(template)).map_err(|_|Error::Full)
}
pub fn batch<const F:usize,const B:usize>(fs:&mut RamFs<F>,
 expected:u64,paths:&[(&[u8],Template)])->Result<u64,Error>{
 if expected!=fs.version(){return Err(Error::Stale);}
 if paths.is_empty(){return Err(Error::Invalid);}
 let mut original=[0u8;B];let n=fs.export_snapshot(&mut original)
  .map_err(|_|Error::Full)?;
 let mut staged=RamFs::<F>::new();
 staged.import_snapshot(&original[..n]).map_err(|_|Error::Invalid)?;
 for (path,template) in paths{
  if path.len()<2||path.len()>PATH_MAX||path[0]!=b'/'||
   staged.metadata(path).is_ok(){return Err(Error::Conflict);}
  if content(*template).len()>CONTENT_MAX{return Err(Error::Full);}
  staged.replace(path,content(*template)).map_err(|_|Error::Full)?;
 }
 let mut updated=[0u8;B];let n=staged.export_snapshot(&mut updated)
  .map_err(|_|Error::Full)?;
 fs.import_snapshot(&updated[..n]).map_err(|_|Error::Invalid)?;
 Ok(fs.version())
}
#[cfg(test)]mod tests{
 use super::*;
 #[test]fn creates_real_rust_source_and_readme_from_templates(){
  let mut fs=RamFs::<2>::new();
  batch::<2,2048>(&mut fs,0,&[(b"/p/main.rs",Template::RustCommand),
   (b"/p/README.md",Template::Readme)]).unwrap();
  assert!(fs.metadata(b"/p/main.rs").is_ok());
  assert!(fs.metadata(b"/p/README.md").is_ok());
 }
 #[test]fn existing_project_source_is_not_overwritten_by_scaffolder(){
  let mut fs=RamFs::<1>::new();fs.replace(b"/a",b"mine").unwrap();
  assert_eq!(generate(&mut fs,1,b"/a",Template::RustLibrary),Err(Error::Conflict));
 }
 #[test]fn no_available_file_slots_refuses_transaction_without_partial_files(){
  let mut fs=RamFs::<1>::new();
  assert_eq!(batch::<1,1024>(&mut fs,0,&[(b"/a",Template::Readme),
   (b"/b",Template::RustCommand)]),Err(Error::Full));
  assert!(fs.metadata(b"/a").is_err());
 }
}
